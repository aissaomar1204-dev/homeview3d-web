// Step 4 — self-host <model-viewer> (no CDN at runtime) + the meshopt decoder trigger file.
//
//   public/lib/model-viewer/model-viewer.min.js   @google/model-viewer dist bundle (includes three.js r183, lit,
//                                                  gainmap-js and three's meshopt decoder) — ES module
//   public/lib/model-viewer/meshopt_decoder.js     meshoptimizer decoder as a classic script (sets self.MeshoptDecoder)
//   public/lib/model-viewer/LICENSE-model-viewer.txt, LICENSE-meshoptimizer.md
//
// Usage: node scripts/3d/vendor-model-viewer.mjs [version]   (default 4.3.1, latest 4.x on 2026-09-28)
// Downloads the npm tarball with `npm pack` (registry.npmjs.org) into a temp dir; nothing is added to package.json.
import { execSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import zlib from 'node:zlib';
import crypto from 'node:crypto';
import { ROOT } from './lib.mjs';

const VERSION = process.argv[2] || '4.3.1';
if (!/^\d+\.\d+\.\d+$/.test(VERSION)) throw new Error(`invalid version ${VERSION}`);
const OUT = path.join(ROOT, 'public/lib/model-viewer');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'mv-'));

/** Minimal .tgz reader (regular files only) so we don't depend on a system `tar`. */
function readTgz(file) {
  const buf = zlib.gunzipSync(fs.readFileSync(file));
  const files = new Map();
  let off = 0;
  while (off + 512 <= buf.length) {
    const name = buf.toString('utf8', off, off + 100).replace(/\0.*$/s, '');
    if (!name) break;
    const size = parseInt(buf.toString('utf8', off + 124, off + 136).replace(/\0.*$/s, '').trim() || '0', 8);
    const type = String.fromCharCode(buf[off + 156] || 48);
    const prefix = buf.toString('utf8', off + 345, off + 500).replace(/\0.*$/s, '');
    if (type === '0' || type === '\0') files.set((prefix ? prefix + '/' : '') + name, buf.subarray(off + 512, off + 512 + size));
    off += 512 + Math.ceil(size / 512) * 512;
  }
  return files;
}

const packJson = execSync(`npm pack @google/model-viewer@${VERSION} --json --pack-destination "${tmp}"`, { encoding: 'utf8' });
const pack = JSON.parse(packJson)[0];
const tgz = path.join(tmp, pack.filename);
const files = readTgz(tgz);
const pkg = JSON.parse(files.get('package/package.json').toString());
if (pkg.license !== 'Apache-2.0') throw new Error(`unexpected license ${pkg.license}`);

fs.mkdirSync(OUT, { recursive: true });
const write = (name, data) => {
  fs.writeFileSync(path.join(OUT, name), data);
  const sha = crypto.createHash('sha384').update(data).digest('base64');
  console.log(`[vendor] ${name.padEnd(28)} ${(data.length / 1024).toFixed(0).padStart(5)} KB  sha384-${sha}`);
};
write('model-viewer.min.js', files.get('package/dist/model-viewer.min.js'));
write('LICENSE-model-viewer.txt', files.get('package/LICENSE'));

// meshoptimizer ships only ESM/CJS builds since 1.0; model-viewer loads meshoptDecoderLocation with a
// classic <script>, so wrap the ESM build into one that defines self.MeshoptDecoder.
const moDir = path.join(ROOT, 'node_modules/meshoptimizer');
const moPkg = JSON.parse(fs.readFileSync(path.join(moDir, 'package.json'), 'utf8'));
const esm = fs.readFileSync(path.join(moDir, 'meshopt_decoder.mjs'), 'utf8');
if (!/export\s*\{\s*MeshoptDecoder\s*\};?\s*$/.test(esm)) throw new Error('meshopt_decoder.mjs layout changed');
const classic = `/*! meshoptimizer ${moPkg.version} decoder (MIT, (c) Arseny Kapoulkine) — classic-script build generated by scripts/3d/vendor-model-viewer.mjs */\n(function () {\n${esm.replace(/export\s*\{\s*MeshoptDecoder\s*\};?\s*$/, '')}\nself.MeshoptDecoder = MeshoptDecoder;\n})();\n`;
write('meshopt_decoder.js', Buffer.from(classic));
write('LICENSE-meshoptimizer.md', fs.readFileSync(path.join(moDir, 'LICENSE.md')));

fs.writeFileSync(path.join(OUT, 'VERSION.json'), JSON.stringify({
  '@google/model-viewer': { version: pkg.version, license: pkg.license, tarball: pack.filename, integrity: pack.integrity, bundles: { three: pkg.peerDependencies?.three, ...pkg.dependencies } },
  meshoptimizer: { version: moPkg.version, license: moPkg.license },
  vendored: new Date().toISOString().slice(0, 10),
}, null, 2));
fs.rmSync(tmp, { recursive: true, force: true });
console.log(`[vendor] @google/model-viewer ${pkg.version} (${pkg.license}) -> ${path.relative(ROOT, OUT)}`);
