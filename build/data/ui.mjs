function mergeViewer(base, extra) {
  if (!extra) return base;
  if (extra.viewer && typeof extra.viewer === 'object') {
    for (const [k, v] of Object.entries(extra)) base[k] = (v && typeof v === 'object' && !Array.isArray(v)) ? { ...(base[k] || {}), ...v } : v;
  } else {
    base.viewer = { ...base.viewer, ...extra };
  }
  return base;
}

